"""Local checkpoints let each notebook start in a fresh Python kernel."""
import pickle
from .config import PROCESSED_DIR

BASE_VARIABLES = [
    'impect_matches','available_matches','players','squads','player_lookup','squad_lookup',
    'season_events','season_durations','season_match_ids','key_columns','midfield_positions',
    'midfield_pool','midfield_profile','midfield_screening','screening_with_samples',
    'initial_review_list','example_match_id',
]
ADVANCED_VARIABLES = ['advanced_kpis_to_load','advanced_sql_keys','advanced_player_summary']

def save_context(name, namespace, variable_names):
    """Persist named objects generated by this workflow, never the whole kernel."""
    missing = [key for key in variable_names if key not in namespace]
    if missing:
        raise KeyError(f'Missing checkpoint inputs: {missing}')
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    target = PROCESSED_DIR / f'{name}.pkl'
    temporary = target.with_suffix('.tmp')
    with temporary.open('wb') as handle:
        pickle.dump({key:namespace[key] for key in variable_names}, handle, protocol=5)
    temporary.replace(target)
    print(f'Saved local checkpoint: {target.name}')

def load_context(name):
    """Read only your own locally generated checkpoint; do not load untrusted pickle files."""
    path = PROCESSED_DIR / f'{name}.pkl'
    if not path.exists():
        raise FileNotFoundError(f'{path.name} is missing. Run the preceding preparation notebook first.')
    with path.open('rb') as handle:
        return pickle.load(handle)
